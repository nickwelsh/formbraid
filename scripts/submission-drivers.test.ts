        options.onCancelToken({ cancel });
        options.onSuccess();
        options.onFinish();
        options.onError({ name: 'Late error.' });
        options.onCancel();
        options.onProgress({ loaded: 24 });
        await expect(result).resolves.toEqual({ status: 'success' });
        ctx.controller.abort();

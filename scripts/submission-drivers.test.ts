interface CallbackContext {
    readonly signal: AbortSignal;
    readonly onProgress: (progress: { loaded: number; total: number; percentage?: number }) => void;
}

interface VisitOptions {
    readonly method: string;
    readonly data: object;
    readonly onBefore: (visit: object) => boolean;
    readonly onCancelToken: (token: { cancel: () => void }) => void;
    readonly onProgress: (progress?: {
        loaded: number;
        total?: number | undefined;
        percentage?: number | undefined;
    }) => void;
    readonly onSuccess: () => void;
    readonly onError: (errors: unknown) => void;
    readonly onCancel: () => void;
    readonly onFinish: () => void;
    readonly onHttpException: (error: unknown) => boolean;
    readonly onNetworkError: (error: unknown) => boolean;
}

const sources = new Map<string, string>();
vi.setConfig({ testTimeout: 10_000 });

function deferred<T>() {
    // The constructor installs these controlled transport/import gates synchronously.
    // oxlint-disable-next-line eslint/init-declarations
    let finish!: (value: T) => void;
    // oxlint-disable-next-line eslint/init-declarations
    let fail!: (reason: unknown) => void;
    // oxlint-disable-next-line promise/avoid-new -- Explicit gates prove cancellation races without timing assumptions.
    const promise = new Promise<T>((resolve, reject) => {
        finish = resolve;
        fail = reject;
    });
    return { promise, resolve: finish, reject: fail };
}

function generate(driver: 'Fetch' | 'Inertia', method: string): string {
    const key = `${driver}:${method}`;
    const cached = sources.get(key);
    if (cached !== undefined) {
        return cached;
    }
    const source = execFileSync(
        'php',
        [
            '-r',
            String.raw`require $argv[1]; $class = "Formbraid\\Laravel\\Drivers\\".$argv[2]; echo (new $class)->generate("endpoint()", $argv[3]);`,
            fileURLToPath(new URL('../packages/laravel/vendor/autoload.php', import.meta.url)),
            driver,
            method,
        ],
        { encoding: 'utf8' },
    );
    sources.set(key, source);
    return source;
}

async function fixture(driver: 'Fetch' | 'Inertia', method = 'post') {
    const effectModule = await import('effect');
    const fetchMock = vi.fn<typeof fetch>().mockResolvedValue(new Response(null, { status: 204 }));
    const router = { visit: vi.fn<(url: string, options: VisitOptions) => void>() };
    const loadInertia = vi.fn<() => Promise<{ router: typeof router }>>().mockResolvedValue({ router });
    const cookieJar = { cookie: '' };
    const window = Object.assign(new EventTarget(), {
        location: { href: 'https://app.test/edit', origin: 'https://app.test' },
    });
    const endpoint = vi.fn<() => string>(() => '/submit');
    // Only the module-loading fixture boundary changes. The callback itself is generated by PHP above.
    const source = generate(driver, method)
        .replace("import('@inertiajs/react')", 'loadInertia()')
        .replace("import('effect')", 'loadEffect()')
        .replace("import('effect/http')", 'loadHttp()');
    const { code } = await transformWithOxc(`(${source})`, 'submission-driver.ts', { lang: 'ts' });
    const candidate: unknown = new Script(code).runInNewContext({
        fetch: fetchMock,
        Blob,
        File,
        FormData,
        URL,
        Date,
        Event,
        CustomEvent,
        queueMicrotask,
        document: cookieJar,
        window,
        endpoint,
        loadInertia,
        loadEffect: async () => await import('effect'),
        loadHttp: async () => {
            const httpModule = await import('effect/http');
            return {
                ...httpModule,
                FetchHttpClient: {
                    ...httpModule.FetchHttpClient,
                    layer: effectModule.Layer.provide(
                        httpModule.FetchHttpClient.layer,
                        effectModule.Layer.succeed(httpModule.FetchHttpClient.Fetch, fetchMock),
                    ),
                },
            };
        },
    });
    if (typeof candidate !== 'function') {
        throw new TypeError('The generated source is not a callback expression.');
    }
    // oxlint-disable-next-line typescript/no-unsafe-type-assertion -- PHP emits the public callback contract; VM evaluation can only verify callability here.
    const generatedSubmit = candidate as (values: object, ctx: CallbackContext) => Promise<unknown>;
    const submit = async (values: object, ctx: CallbackContext): Promise<unknown> => {
        const result = await generatedSubmit(values, ctx);
        return result;
    };
    return { submit, fetchMock, cookieJar, window, endpoint, router, loadInertia };
}

function context() {
    const controller = new AbortController();
    const add = vi.spyOn(controller.signal, 'addEventListener');
    const remove = vi.spyOn(controller.signal, 'removeEventListener');
    const onProgress = vi.fn<CallbackContext['onProgress']>();
    return { controller, add, remove, onProgress, signal: controller.signal };
}

function requestOptions(mock: ReturnType<typeof vi.fn<typeof fetch>>, index = 0): RequestInit {
    const options = mock.mock.calls[index]?.[1];
    if (options === undefined) {
        throw new Error('The fetch callback did not provide request options.');
    }
    return options;
}

function visitOptions(mock: ReturnType<typeof vi.fn<(url: string, options: VisitOptions) => void>>): VisitOptions {
    const options = mock.mock.calls[0]?.[1];
    if (options === undefined) {
        throw new Error('The Inertia callback did not start a visit.');
    }
    return options;
}

function multipartBody(options: RequestInit): FormData {
    if (!(options.body instanceof FormData)) {
        throw new TypeError('Expected multipart FormData.');
    }
    return options.body;
}

function uploadedFile(body: FormData, key: string): File {
    const value = body.get(key);
    if (!(value instanceof File)) {
        throw new TypeError(`Expected an uploaded file at ${key}.`);
    }
    return value;
}

function requestUrl(mock: ReturnType<typeof vi.fn<typeof fetch>>): URL {
    const input = mock.mock.calls[0]?.[0];
    if (typeof input !== 'string' && !(input instanceof URL)) {
        throw new TypeError('Expected a request URL.');
    }
    return new URL(input);
}

function spoofedMethod(method: string): string | null {
    return method === 'post' ? null : method;
}

function inertiaData(values: object, method: string): object {
    return method === 'post' ? values : { ...values, _method: method };
}

function dispatchBefore(window: EventTarget, options: VisitOptions): void {
    const visit = {};
    if (options.onBefore(visit)) {
        window.dispatchEvent(new CustomEvent('inertia:before', { detail: { visit }, cancelable: true }));
    }
}


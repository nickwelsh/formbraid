<?php

declare(strict_types=1);

namespace Formbraid\Laravel;

use Formbraid\Laravel\Contracts\SubmissionDriver;
use Illuminate\Routing\Router;
use RuntimeException;

final readonly class ControllerEmitter
{
    public function __construct(private SubmissionDriver $driver) {}

    /**
     * @param  list<class-string>  $requests
     * @return array<string, string> Paths relative to the configured output directory.
     */
    public function emit(Router $router, array $requests): array
    {
        $modules = [];
        foreach (HttpOperationsCommand::operations($router, true) as $operation) {
            if (! in_array($operation['schema'], $requests, true)) {
                continue;
            }
            $routeParts = explode('.', $operation['name']);
            $action = $operation['action'] ?? array_pop($routeParts);
            if (! preg_match('/^[A-Za-z_]\w*$/D', $action)) {
                throw new RuntimeException("Unsupported route action: {$operation['name']}");
            }
            $controller = $operation['controller'] ?? 'Routes\\'.implode('\\', $routeParts ?: ['Operations']);
            $path = 'controllers/'.FormEmitter::path($controller);
            $requestPath = 'requests/'.FormEmitter::path($operation['schema']);
            $from = explode('/', dirname($path));
            $to = explode('/', substr($requestPath, 0, -3).'.js');
            while ($from !== [] && $to !== [] && $from[0] === $to[0]) {
                array_shift($from);
                array_shift($to);
            }
            $relative = str_repeat('../', count($from)).implode('/', $to);
            if (! str_starts_with($relative, '.')) {
                $relative = './'.$relative;
            }
            $entries = $modules[$path] ?? [];
            if (isset($entries[$action])) {
                throw new RuntimeException("Duplicate controller form export {$controller}::{$action}. Give each form route a distinct controller action.");
            }
            // Per-action import aliases also support two requests with the same short class name.
            $alias = '_form_'.$action;
            $values = '_values_'.$action;
            $name = FormEmitter::name($operation['schema']);
            $imports = 'import { '.$name.' as '.$alias.' } from '.TypeShape::literal($relative).";\n".
                'import type { '.$name.'Values as '.$values.' } from '.TypeShape::literal($relative).';';
            $params = [];
            foreach ($operation['parameters'] as $parameter) {
                $uri = $operation['binding']['uri'];
                if (! preg_match('/^\w+$/D', $parameter['name']) ||
                    ! str_contains($uri, '{'.$parameter['name'].'}') && ! str_contains($uri, '{'.$parameter['name'].'?}')) {
                    throw new RuntimeException("Unsupported route parameter {$parameter['name']} for {$operation['name']}: only URI parameters supported by routeUrl can be generated.");
                }
                $params[] = TypeShape::literal($parameter['name']).($parameter['optional'] ? '?' : '').': string | number;';
            }
            $endpoint = 'routeUrl('.TypeShape::literal($operation['binding']['uri']).', '.($params === [] ? '{}' : 'parameters').')';
            $callback = $this->driver->generate($endpoint, $operation['binding']['method']);
            if (trim($callback) === '') {
                throw new RuntimeException('The submission driver returned an empty TypeScript callback.');
            }
            $descriptor = "({ version: 1 as const, definition: {$alias}, submission: { submit: {$callback} } } satisfies FormDescriptor<{$values}, typeof {$alias}.fields, typeof {$alias}.groups>)";
            $expression = $params === [] ? $descriptor : '(parameters: { '.implode(' ', $params).' }) => '.$descriptor;
            // Export specifiers can be reserved words, unlike const identifiers.
            $entries[$action] = $imports."\nconst _action_{$action} = {$expression};\nexport { _action_{$action} as {$action} };";
            $modules[$path] = $entries;
        }
        $files = [];
        foreach ($modules as $path => $entries) {
            $files[$path] = "// Generated by Formbraid.\nimport { routeUrl } from '@formbraid/core';\nimport type { FormDescriptor } from '@formbraid/core';\n\n".implode("\n\n", $entries)."\n";
        }

        return $files;
    }
}

<?php

declare(strict_types=1);

namespace Formbraid\Laravel;

use RuntimeException;
use stdClass;

final readonly class ComponentEnum
{
    public function __construct(public string $class, public string $source) {}

    public static function generate(string $path, ComponentMetadata $metadata): self
    {
        $composerPath = base_path('composer.json');
        $source = is_file($composerPath) ? file_get_contents($composerPath) : false;
        $composer = $source === false ? null : json_decode($source, flags: JSON_THROW_ON_ERROR);
        if (! $composer instanceof stdClass) {
            throw new RuntimeException('Cannot infer component enum namespace without composer.json.');
        }
        $mappings = [];
        foreach (['autoload', 'autoload-dev'] as $section) {
            $autoload = $composer->{$section} ?? null;
            $prefixes = $autoload instanceof stdClass ? ($autoload->{'psr-4'} ?? null) : null;
            if (! $prefixes instanceof stdClass) {
                continue;
            }
            foreach (get_object_vars($prefixes) as $prefix => $directories) {
                foreach (is_array($directories) ? $directories : [$directories] as $directory) {
                    if (! is_string($directory)) {
                        throw new RuntimeException('Invalid Composer PSR-4 path mapping.');
                    }
                    $directory = trim(str_replace('\\', '/', $directory), '/');
                    while (str_starts_with($directory, './')) {
                        $directory = substr($directory, 2);
                    }
                    if ($directory === '.') {
                        $directory = '';
                    }
                    $relative = $directory === '' ? $path : (str_starts_with($path, $directory.'/') ? substr($path, strlen($directory) + 1) : null);
                    if ($relative !== null) {
                        $mappings[$directory] = $prefix.str_replace('/', '\\', substr($relative, 0, -4));
                    }
                }
            }
        }
        uksort($mappings, static fn (string $left, string $right): int => strlen($right) <=> strlen($left));
        $class = array_values($mappings)[0] ?? throw new RuntimeException("No Composer PSR-4 path mapping for component_enum {$path}.");
        FormEmitter::path($class);
        $parts = explode('\\', $class);
        $name = array_pop($parts);
        $namespace = implode('\\', $parts);
        $keys = array_values(array_unique(array_map(strval(...), [...array_keys($metadata->fields), ...array_keys($metadata->components), ...array_keys($metadata->groups)])));
        sort($keys);
        $cases = [];
        $names = [];
        foreach ($keys as $key) {
            $case = preg_replace('/[^A-Za-z0-9_]/', '_', $key) ?? '';
            if ($case === '' || ctype_digit($case[0])) {
                $case = '_'.$case;
            }
            // PHP enum cases are identifiers, but cannot use class or built-in enum members.
            if (in_array(strtolower($case), ['class', 'cases', 'from', 'tryfrom'], true)) {
                $case = '_'.$case;
            }
            if (isset($names[$case])) {
                throw new RuntimeException("Component keys collide as enum case {$case}.");
            }
            $names[$case] = $key;
            $cases[] = '    case '.$case.' = '.var_export($key, true).';';
        }
        $header = "<?php\n\ndeclare(strict_types=1);\n\n// Generated by Formbraid.\n";
        $php = $header.($namespace === '' ? '' : "\nnamespace {$namespace};\n\n")."enum {$name}: string\n{\n".implode("\n", $cases)."\n}\n";

        return new self($class, $php);
    }

    /** Load a staged enum before evaluating fields(), without publishing an incomplete generation. */
    public function load(): void
    {
        if (enum_exists($this->class, false)) {
            if ((new \ReflectionEnum($this->class))->getBackingType()?->getName() !== 'string') {
                throw new RuntimeException('The component enum must be a string-backed enum.');
            }

            // PHP configuration can autoload the previous enum. Existing cases still name components;
            // metadata validates those names, and publication makes new cases available next process.
            return;
        }
        if (class_exists($this->class, false) || interface_exists($this->class, false) || trait_exists($this->class, false)) {
            throw new RuntimeException("The component enum class name is already in use: {$this->class}");
        }
        $temporary = tempnam(sys_get_temp_dir(), 'formbraid-enum-');
        if ($temporary === false) {
            throw new RuntimeException('Cannot stage the component enum.');
        }
        try {
            if (file_put_contents($temporary, $this->source) === false) {
                throw new RuntimeException('Cannot stage the component enum.');
            }
            require $temporary;
        } finally {
            unlink($temporary);
        }
    }
}

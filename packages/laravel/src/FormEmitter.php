<?php

declare(strict_types=1);

namespace Formbraid\Laravel;

use RuntimeException;
use stdClass;

/**
 * @phpstan-import-type ComponentInfo from ComponentMetadata
 *
 * @phpstan-type FieldData array{name: string, type: string, component: string, label: string, props: stdClass, constraints: stdClass&object{options?: list<string|int|float>}, nullable: bool, helpText?: string}
 * @phpstan-type GroupData array{component: string, props: stdClass, fields: stdClass, label?: string, helpText?: string}
 * @phpstan-type FormData array{id: class-string, defaultValues: stdClass, fields: stdClass, groups: stdClass}
 */
final readonly class FormEmitter
{
    public function __construct(private ComponentMetadata $metadata) {}

    /** @param FormData $form */
    public function emit(array $form): string
    {
        // RequestExtractor owns these internal JSON representations.
        /** @var array<string, FieldData> $fields */
        $fields = (array) $form['fields'];
        /** @var array<string, GroupData> $groups */
        $groups = (array) $form['groups'];
        $values = new ValueNode;
        foreach ($fields as $field) {
            $values->insert(explode('.', $field['name']), $this->fieldShape($field), match ($field['type']) {
                'array' => true, 'object' => false, default => null,
            });
        }
        // Match JSON's distinction between associative PHP arrays (objects) and lists.
        $values->resolve([json_decode(TypeShape::literal($form['defaultValues']), flags: JSON_THROW_ON_ERROR)]);
        foreach ($fields as $field) {
            $name = $form['id'].'.'.$field['name'];
            $component = $this->metadata->fields[$field['component']] ?? throw new RuntimeException("{$name}: unregistered field component {$field['component']}.");
            $props = array_replace((array) $field['props'], ['label' => $field['label'], 'constraints' => $field['constraints']]);
            if (isset($field['helpText'])) {
                $props['helpText'] = $field['helpText'];
            }
            $this->validateProps($name, $props, $component);
        }
        foreach ($groups as $key => $group) {
            $name = $form['id'].'.'.$key;
            $component = $this->metadata->groups[$group['component']] ?? throw new RuntimeException("{$name}: unregistered group {$group['component']}.");
            $props = (array) $group['props'];
            foreach (['label', 'helpText'] as $prop) {
                if (isset($group[$prop])) {
                    $props[$prop] = $group[$prop];
                }
            }
            $this->validateProps($name, $props, $component);
            $slots = $component['slots'] ?? throw new RuntimeException("{$group['component']}: group slots could not be inspected. Export a group created with withFieldGroup({ defaultValues, ... }).");
            foreach ($slots as $slot => $type) {
                if (! property_exists($group['fields'], (string) $slot)) {
                    throw new RuntimeException("{$name}: missing group slot {$slot}.");
                }
            }
            foreach (get_object_vars($group['fields']) as $slot => $target) {
                if (! is_string($target) || ! isset($slots[$slot], $fields[$target])) {
                    throw new RuntimeException("{$name}: invalid group slot or field {$slot}.");
                }
                $node = $values->writable($target);
                $type = $slots[$slot];
                if (str_contains($target, '*') || $node === null || ! $type->inspectable() ||
                    ! $node->shape()->assignableTo($type) || ! $type->assignableTo($node->shape())) {
                    throw new RuntimeException("{$name}.{$slot}: incompatible field value type for {$target}.");
                }
            }
        }
        $name = self::name($form['id']);

        return "// Generated by Formbraid. Edit the FormRequest or configuration.\nimport { defineForm } from '@formbraid/core';\n\nexport type {$name}Values = ".$values->shape()->typescript().";\n\nconst _definition = defineForm<{$name}Values>()(".TypeShape::literal($form, true).");\nexport { _definition as {$name} };\n";
    }

    /**
     * @param  array<array-key, mixed>  $values
     * @param  ComponentInfo  $component
     */
    private function validateProps(string $name, array $values, array $component): void
    {
        foreach ($values as $key => $value) {
            $prop = $component['props'][$key] ?? throw new RuntimeException("{$name}: unknown component prop {$key}.");
            if (! $prop['type']->accepts(json_decode(TypeShape::literal($value), flags: JSON_THROW_ON_ERROR))) {
                throw new RuntimeException("{$name}: {$key} does not match the component prop type.");
            }
        }
        foreach ($component['props'] as $key => $prop) {
            if ($prop['required'] && ! array_key_exists($key, $values)) {
                throw new RuntimeException("{$name}: missing required component prop {$key}.");
            }
        }
    }

    /** @param FieldData $field */
    private function fieldShape(array $field): TypeShape
    {
        $options = $field['constraints']->options ?? null;
        $type = new TypeShape(match ($field['type']) {
            'integer', 'number' => 'number', 'date', 'string' => 'string', 'enum' => $options === null ? 'string' : 'union', default => $field['type'],
        });
        if ($field['type'] === 'enum' && $options !== null) {
            $type->alternatives = array_map(static fn (mixed $value): TypeShape => new TypeShape('literal', $value), [...$options, '']);
        }
        if ($field['type'] === 'array' || $field['type'] === 'object') {
            $item = new TypeShape($options === null ? 'unknown' : 'union');
            if ($options !== null) {
                $variants = [];
                foreach ($options as $option) {
                    $variants[TypeShape::literal($option)] = new TypeShape('literal', $option);
                    if (is_int($option) || is_float($option)) {
                        $variants[TypeShape::literal((string) $option)] = new TypeShape('literal', (string) $option);
                    } elseif (is_numeric($option) && (string) (0 + $option) === $option) {
                        $variants[TypeShape::literal(0 + $option)] = new TypeShape('literal', 0 + $option);
                    }
                }
                $item->alternatives = array_values($variants);
            }
            if ($field['type'] === 'array') {
                $type->items = $item;
            } else {
                $type->additionalProperties = $item;
            }
        }
        if (! $field['nullable'] && $field['type'] !== 'file') {
            return $type;
        }
        $nullable = new TypeShape('union');
        $nullable->alternatives = [$type, new TypeShape('null')];

        return $nullable;
    }

    public static function name(string $class): string
    {
        $parts = explode('\\', $class);

        return array_pop($parts);
    }

    public static function path(string $class): string
    {
        if (! preg_match('/^[A-Za-z_]\w*(?:\\\\[A-Za-z_]\w*)*$/D', $class)) {
            throw new RuntimeException("Invalid PHP class name: {$class}");
        }

        return str_replace('\\', '/', $class).'.ts';
    }
}
